#requires -Version 5.1
<#
.SYNOPSIS
  Generates src/SimpleRay.App/Localization/LocKeys.g.cs from en.json — a compile-time
  constant per localization key (value == the JSON key), so C# key references are typo-safe.
  Deterministic; throws on identifier collisions. Re-run after adding/removing keys
  (loc-add-key.ps1 does this for you). A unit test verifies the file stays in sync.
#>
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$enPath = Join-Path $root "src\SimpleRay.App\Localization\langs\en.json"
$outPath = Join-Path $root "src\SimpleRay.App\Localization\LocKeys.g.cs"

$en = Get-Content $enPath -Raw -Encoding UTF8 | ConvertFrom-Json
$keys = $en.PSObject.Properties.Name

function To-Identifier([string]$key) {
    ($key -split '\.' | ForEach-Object {
        if ($_.Length -eq 0) { "" } else { $_.Substring(0, 1).ToUpperInvariant() + $_.Substring(1) }
    }) -join ''
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("// <auto-generated>")
[void]$sb.AppendLine("// Generated from Localization/langs/en.json by scripts/gen-lockeys.ps1 - do not edit by hand.")
[void]$sb.AppendLine("// </auto-generated>")
[void]$sb.AppendLine("namespace SimpleRay.App.Localization;")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("/// <summary>Compile-time constants for every localization key (each value is the JSON key).</summary>")
[void]$sb.AppendLine("public static class LocKeys")
[void]$sb.AppendLine("{")

$seen = @{}
foreach ($k in $keys) {
    $id = To-Identifier $k
    if ($seen.ContainsKey($id)) { throw "Identifier collision '$id' from keys '$k' and '$($seen[$id])'" }
    $seen[$id] = $k
    [void]$sb.AppendLine("    /// <summary>$k</summary>")
    [void]$sb.AppendLine("    public const string $id = ""$k"";")
}
[void]$sb.AppendLine("}")

[System.IO.File]::WriteAllText($outPath, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated $($keys.Count) keys -> $outPath"
